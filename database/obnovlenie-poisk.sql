-- Поиск по всему сайту.
--
-- Выполняется один раз на уже работающей базе: phpMyAdmin → выбрать базу →
-- вкладка «SQL» → вставить это и нажать «Вперёд».
--
-- Таблица одна на весь сайт: и страницы услуг, решений, кейсов и тарифов,
-- и статьи. Страницы собираются из файлов текстов, статьи — из своей
-- таблицы; дальше поиск не различает, откуда что пришло, и одной выборкой
-- отвечает на запрос по всему сайту.
--
-- Сразу после импорта таблица пуста и поиск ничего не находит. Наполняет
-- её кнопка «Обновить поиск» в админке — её же нажимают после каждой
-- выкладки обновления с новыми или изменёнными страницами.

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS search_index (
    id         INT UNSIGNED NOT NULL AUTO_INCREMENT,
    -- Адрес страницы на сайте, с ведущим слэшем: /uslugi/vnedrenie-bitrix24.
    url        VARCHAR(255) NOT NULL,
    -- Подпись раздела в выдаче: «Услуги · Битрикс24», «Кейсы», «Статьи».
    section    VARCHAR(80)  NOT NULL DEFAULT '',
    title      VARCHAR(250) NOT NULL,
    -- Первая строка под заголовком. Показывается, когда искомое слово
    -- нашлось в заголовке: кусок текста вокруг него тогда не нужен.
    excerpt    VARCHAR(600) NOT NULL DEFAULT '',
    -- Весь текст страницы без разметки — то, по чему идёт поиск.
    body       MEDIUMTEXT   NOT NULL,
    -- Чем больше, тем выше страница в выдаче при равном совпадении:
    -- услуга полезнее статьи, статья полезнее правовой страницы.
    weight     TINYINT UNSIGNED NOT NULL DEFAULT 0,
    -- Когда страница попала в указатель. Админка показывает самое свежее
    -- значение — по нему видно, обновляли поиск после выкладки или нет.
    indexed_at DATETIME     NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY search_index_url (url)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
