     *
     * Поэтому услуги, которых в списке нет, добавляются сюда сами — с текстом
     * для выдачи вместо перечня работ. Карточка выходит скромная, но страница
     * видна и на неё ведёт ссылка. Дописали состав работ руками — карточка
     * встала на своё место в нужном порядке.
     *
     * @param  list<array<string, mixed>> $items
     * @return list<array<string, mixed>>
     */
    private static function withMissing(array $items): array
    {
        $described = array_column($items, 'slug');

        foreach (self::PAGES as $slug => $page) {
            if (in_array($slug, $described, true)) {
                continue;
            }

            $items[] = [
                'slug'      => $slug,
                'href'      => '/uslugi/' . $slug,
                'title'     => $page['crumb'],
                'situation' => $page['description'],
                'points'    => [],
            ];
        }

        return $items;
    }

    public function index(): void
    {
        $page = $this->content('services');
        $page['items'] = self::withMissing($page['items']);

        $this->html($this->view->render('services', [
            'styles' => ['css/pages.css'],
            'seo' => [
                'title'       => 'Услуги: внедрение, аудит и сопровождение CRM',
                'description' => 'Внедрение Битрикс24 и amoCRM, аудит CRM и разбор '
                    . 'конкретной системы, настройка и доработка действующей, '
                    . 'интеграции с телефонией, сайтом, 1С и Мой склад, '
                    . 'ежемесячное сопровождение.',
                'canonical'   => $this->url('/uslugi'),
                'breadcrumbs' => [
                    ['label' => 'Главная', 'href' => '/'],
                    ['label' => 'Услуги',  'href' => '/uslugi'],
                ],
                // Состав раздела: какие услуги в нём и по каким адресам.
                'page_type' => 'CollectionPage',
                'jsonld'    => [Schema::itemList(
                    $this->config['base_url'],
                    $this->url('/uslugi'),
                    array_map(
                        static fn (array $item): array => [
                            'name' => $item['title'],
                            'href' => $item['href'],
                        ],
                        $page['items'],
                    ),
                )],
            ],
            'page' => $page,
            'form' => $this->formFlash(),
        ]));
    }

    public function show(string $slug): void
    {
        $meta = self::PAGES[$slug] ?? null;

        // Адрес вида /uslugi/что-угодно не должен отдавать пустую страницу
        // с кодом 200: для поиска это дубль, для посетителя — тупик.
        if ($meta === null) {
            $this->notFound();
            return;
        }

        $page = $this->content($meta['content']);

        // Вопросы и ответы уходят в микроразметку, если они у услуги есть.
        //
        // Узел добавляется отдельной строкой, а не через сложение массивов:
        // у обоих узлов ключ 0, и при сложении второй молча пропадает.
        // На статьях это уже случалось — здесь сразу сделано правильно.
        $jsonld = [[
            '@type' => 'Service',
            '@id'   => $this->url('/uslugi/' . $slug) . '#service',
            'name'        => $meta['crumb'],
            'description' => $meta['description'],
            'serviceType' => $meta['crumb'],
            'provider'    => ['@id' => $this->config['base_url'] . '/#organization'],
            'url'         => $this->url('/uslugi/' . $slug),
        ]];

        if (!empty($page['faq']['items'])) {
            $jsonld[] = Schema::faq(
                $this->url('/uslugi/' . $slug),
                $page['faq']['items'],
            );
        }

        $this->html($this->view->render('service', [
            'styles' => ['css/pages.css'],
            'seo' => [
                'title'       => $meta['title'],
                'description' => $meta['description'],
                'canonical'   => $this->url('/uslugi/' . $slug),
                'breadcrumbs' => [
                    ['label' => 'Главная',        'href' => '/'],
                    ['label' => 'Услуги',         'href' => '/uslugi'],
                    ['label' => $meta['crumb'],   'href' => '/uslugi/' . $slug],
                ],
                // Услуга как услуга, а не просто страница: поисковик видит,
                // что именно оказывается и кем. Плюс вопросы, если есть.
                'jsonld' => $jsonld,
            ],
            'page' => $page,
            'form' => $this->formFlash(),
        ]));
    }

    /** Адреса готовых страниц услуг — для карты сайта. */
    public static function paths(): array
    {
        return array_map(
            static fn (string $slug): string => '/uslugi/' . $slug,
            array_keys(self::PAGES),
        );
    }
