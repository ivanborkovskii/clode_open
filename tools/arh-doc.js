/** Обычный абзац. */
const p = (text, opts = {}) => new Paragraph({
  spacing: { after: opts.after ?? 140, line: 276 },
  alignment: opts.align,
  children: [new TextRun({
    text,
    bold: opts.bold,
    italics: opts.italics,
    color: opts.color,
    size: opts.size,
    font: opts.font,
  })],
});

/** Абзац из нескольких кусков — часть текста жирная или моноширинная. */
const rich = (parts, opts = {}) => new Paragraph({
  spacing: { after: opts.after ?? 140, line: 276 },
  children: parts.map(part => (typeof part === 'string'
    ? new TextRun({ text: part })
    : new TextRun({
      text: part.t,
      bold: part.b,
      italics: part.i,
      color: part.c,
      font: part.mono ? 'Consolas' : undefined,
      size: part.mono ? 19 : undefined,
    }))),
});

