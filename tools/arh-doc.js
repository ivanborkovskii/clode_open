/** Пункт маркированного списка. */
const li = (text, instance = 0) => new Paragraph({
  numbering: { reference: 'tochki', level: 0, instance },
  spacing: { after: 80, line: 276 },
  children: [new TextRun(text)],
});

/** Пункт нумерованного списка — для пошаговых разборов. */
const step = (text, instance) => new Paragraph({
  numbering: { reference: 'shagi', level: 0, instance },
  spacing: { after: 100, line: 276 },
  children: [new TextRun(text)],
});

/**
 * Блок кода или схема папок.
 *
 * Перенос строки внутри абзаца Word не понимает: символ \n в тексте
 * просто пропадёт, и схема схлопнется в одну строку. Поэтому каждая
 * строка — отдельный кусок с явным переносом перед ним.
 */
const code = text => new Paragraph({
  spacing: { after: 140, line: 240 },
  shading: { type: ShadingType.CLEAR, fill: FON },
  indent: { left: 220, right: 220 },
  border: {
    top: { style: BorderStyle.SINGLE, size: 2, color: FON },
    bottom: { style: BorderStyle.SINGLE, size: 2, color: FON },
    left: { style: BorderStyle.SINGLE, size: 12, color: SINIY },
    right: { style: BorderStyle.SINGLE, size: 2, color: FON },
  },
  children: text.split('\n').map((line, i) => new TextRun({
    text: line,
    font: 'Consolas',
    size: 18,
    ...(i > 0 ? { break: 1 } : {}),
  })),
});

const SHIRINA = 9360; // ширина текста на листе A4 с полями 2 см, в твипах

/**
 * Таблица «слева имя, справа объяснение».
 *
 * @param {Array<[string, string]>} rows
 */
const tabl = (head, rows, levaya = 3000) => {
  const pravaya = SHIRINA - levaya;

  const cell = (text, { bold, mono, fill, width }) => new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: fill ? { type: ShadingType.CLEAR, fill } : undefined,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({
      spacing: { after: 0, line: 260 },
      children: [new TextRun({
        text,
        bold,
        font: mono ? 'Consolas' : undefined,
        size: mono ? 18 : 20,
      })],
    })],
  });

  return new Table({
    width: { size: SHIRINA, type: WidthType.DXA },
    columnWidths: [levaya, pravaya],
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: LINIYA },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: LINIYA },
      left: { style: BorderStyle.SINGLE, size: 4, color: LINIYA },
      right: { style: BorderStyle.SINGLE, size: 4, color: LINIYA },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 4, color: LINIYA },
      insideVertical: { style: BorderStyle.SINGLE, size: 4, color: LINIYA },
    },
    rows: [
      new TableRow({
        tableHeader: true,
        children: [
          cell(head[0], { bold: true, fill: FON, width: levaya }),
          cell(head[1], { bold: true, fill: FON, width: pravaya }),
        ],
      }),
      ...rows.map(([a, b]) => new TableRow({
        children: [
          cell(a, { mono: true, width: levaya }),
          cell(b, { width: pravaya }),
        ],
      })),
    ],
  });
};

